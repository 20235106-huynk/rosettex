def hermes_package(root: Path, skill_text: str) -> dict[Path, str]:
    """plugins/hermes/: the root plugin.json and mcp.json, the skill, a README and the LICENSE."""
    m = render_manifests(__version__)
    d = root / "plugins" / "hermes"
    return {
        d / "plugin.json": m["plugin.json"],
        d / "mcp.json": m["mcp.json"],
        d / "skills" / "rosettex" / "SKILL.md": skill_text,
        d / "README.md": HERMES_README,
        d / "LICENSE": (root / "LICENSE").read_text(encoding="utf-8"),
    }


def get_skill_locations(home: Path | None = None) -> list[Path]:
    base = home if home is not None else Path(os.environ.get("HOME", str(Path.home())))
    return [
        base / ".agents" / "skills" / "rosettex",
        base / ".claude" / "skills" / "rosettex",
        base / ".gemini" / "config" / "skills" / "rosettex",
        *[base / h / "skills" / "rosettex" for h in EXTRA_SKILL_HOMES if (base / h).is_dir()],
    ]


def render_manifests(version: str) -> dict[str, str]:
    """Every plugin manifest at the repo root, from the version and DESCRIPTION. Path (relative to the root) -> text."""
    server = {
        "command": "uvx",
        "args": ["--from", f"git+{REPO}@v{version}", "rosettex-mcp"],
    }
    typed = {"rosettex": {"type": "stdio", **server}}  # Agent Plugins and Claude Code
    bare = {"rosettex": server}  # Antigravity and Gemini CLI
    author = {"name": OWNER, "url": f"https://github.com/{OWNER}"}
    common = {"name": "rosettex", "version": version, "description": DESCRIPTION}
    meta = {"author": author, "homepage": REPO, "repository": REPO, "license": "MIT", "keywords": KEYWORDS}
    files = {
        "plugin.json": {"$schema": f"{SCHEMAS}/plugin.schema.json", **common, **meta},
        "mcp.json": {"$schema": f"{SCHEMAS}/mcp.schema.json", "mcpServers": typed},
        ".claude-plugin/plugin.json": {**common, **meta},
        ".claude-plugin/marketplace.json": {
            "name": "rosettex",
            "owner": {"name": OWNER},
            "description": DESCRIPTION,
            "plugins": [{"name": "rosettex", "source": "./", "description": DESCRIPTION, "version": version}],
        },
        ".mcp.json": {"mcpServers": typed},
        ".antigravity-plugin/plugin.json": {**common, **meta},
        "mcp_config.json": {"mcpServers": bare},
        "gemini-extension.json": {**common, "mcpServers": bare},
        "server.json": {  # MCP Registry; needs the package on PyPI (see .github/workflows/release.yml)
            "$schema": "https://static.modelcontextprotocol.io/schemas/2025-12-11/server.schema.json",
            "name": f"io.github.{OWNER}/rosettex",
            "description": "Translate scientific papers (TeX source or born-digital PDF) and rebuild the PDF with its layout.",
            "repository": {"url": REPO, "source": "github"},
            "version": version,
            "packages": [
                {
                    "registryType": "pypi",
                    "identifier": "rosettex",
                    "version": version,
                    "runtimeHint": "uvx",
                    "runtimeArguments": [{"type": "named", "name": "--from", "value": f"rosettex=={version}"}],
                    "packageArguments": [{"type": "positional", "value": "rosettex-mcp"}],
                    "transport": {"type": "stdio"},
                }
            ],
        },
        ".agents/plugins/marketplace.json": {
            "name": "rosettex",
            "interface": {"displayName": "rosettex"},
            "plugins": [
                {
                    "name": "rosettex",
                    "source": {"source": "local", "path": "./"},
                    "policy": {"installation": "AVAILABLE", "authentication": "ON_INSTALL"},
                    "category": "Productivity",
                }
            ],
        },
    }
    return {path: json.dumps(doc, indent=2, ensure_ascii=False) + "\n" for path, doc in files.items()}


def _copy_tree_or_write(loc: Path, content: str) -> None:
    loc.mkdir(parents=True, exist_ok=True)
    try:
        cand = resources.files("rosettex.data").joinpath("skill", "rosettex")
        if cand.is_dir():
            for item in cand.iterdir():
                if item.name == "SKILL.md":
                    continue
                dest = loc / item.name
                if item.is_file():
                    shutil.copy2(item, dest)
                elif item.is_dir():
                    shutil.copytree(item, dest, dirs_exist_ok=True)
    except Exception:
        pass
    (loc / "SKILL.md").write_text(content, encoding="utf-8")


def install_skill(
    remove: bool = False, force: bool = False, home: Path | None = None
) -> list[dict]:
    locations = get_skill_locations(home)
    results: list[dict] = []

    if remove:
        for loc in locations:
            if not loc.exists():
                results.append({"path": str(loc), "status": "skipped", "reason": "not installed"})
                continue
            skill_file = loc / "SKILL.md"
            if not skill_file.is_file():
                results.append(
                    {
                        "path": str(loc),
                        "status": "skipped",
                        "reason": "missing SKILL.md",
                    }
                )
                continue
            text = skill_file.read_text(encoding="utf-8")
            name_match = re.search(r"^\s*name:\s*rosettex\s*$", text, re.MULTILINE)
            ver_match = re.search(r"^\s*rosettex-version:\s*", text, re.MULTILINE)
            if name_match and ver_match:
                shutil.rmtree(loc)
                results.append({"path": str(loc), "status": "removed"})
            else:
                results.append(
                    {
                        "path": str(loc),
                        "status": "skipped",
                        "reason": "not a rosettex skill (missing name: rosettex or rosettex-version)",
                    }
                )
        return results

    content = render_skill(__version__)
    for loc in locations:
        skill_file = loc / "SKILL.md"
        if not loc.exists():
            _copy_tree_or_write(loc, content)
            results.append({"path": str(loc), "status": "installed"})
            continue

        if not skill_file.is_file():
            if not force:
                results.append(
                    {
                        "path": str(loc),
                        "status": "skipped",
                        "reason": "existing directory has no SKILL.md (use --force to overwrite)",
                    }
                )
                continue
            _copy_tree_or_write(loc, content)
            results.append({"path": str(loc), "status": "installed"})
            continue

        text = skill_file.read_text(encoding="utf-8")
        name_match = re.search(r"^\s*name:\s*rosettex\s*$", text, re.MULTILINE)
        ver_match = re.search(
            r"^\s*rosettex-version:\s*[\"']?([^\"'\n]+)[\"']?", text, re.MULTILINE
        )
        existing_version = ver_match.group(1).strip() if ver_match else None

        if not name_match:
            if not force:
                results.append(
                    {
                        "path": str(loc),
                        "status": "skipped",
                        "reason": "not a rosettex skill (use --force to overwrite)",
                    }
                )
                continue
        elif existing_version != __version__:
            if not force:
                results.append(
                    {
                        "path": str(loc),
                        "status": "skipped",
                        "reason": f"version mismatch: {existing_version or 'absent'} (use --force to overwrite)",
                    }
                )
                continue
        else:
            if text == content:
                results.append({"path": str(loc), "status": "up to date"})
                continue

        _copy_tree_or_write(loc, content)
        results.append({"path": str(loc), "status": "updated"})

    return results


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(prog="rosettex.skill")
    parser.add_argument("--check", action="store_true", help="exit 1 when a generated file differs from its source (CI)")
    a = parser.parse_args(argv)

    content = render_skill(__version__)
    root = Path(__file__).resolve().parents[2]
    # Generated: the repo skill (the plugin's one skill), the package data copy, and every root manifest
    copies = {
        root / "skills" / "rosettex" / "SKILL.md": content,
        root / "src" / "rosettex" / "data" / "skill" / "rosettex" / "SKILL.md": content,
        **{root / path: text for path, text in render_manifests(__version__).items()},
        **hermes_package(root, content),
    }
    if a.check:
        stale = [str(p) for p, text in copies.items() if not p.is_file() or p.read_text(encoding="utf-8") != text]
        for p in stale:
            print(f"stale: {p} (run: uv run python -m rosettex.skill)", file=sys.stderr)
        return 1 if stale else 0
    for p, text in copies.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    print(f"Wrote {len(copies)} generated files (skill: {len(content)} characters)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
